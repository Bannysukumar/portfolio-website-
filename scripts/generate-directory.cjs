/* Generates src/data/directory.ts — the canonical, fully-typed directory of
 * every public repository — by merging:
 *   scripts/inventory.json            (GitHub API snapshot)
 *   scripts/directory-overrides.json  (curated display names, tech lines,
 *                                      verified live URLs, dead-deploy notes)
 *
 * Safe to re-run; never produces duplicates (one entry per inventory repo).
 * Usage: node scripts/fetch-inventory.cjs && node scripts/generate-directory.cjs
 */
const fs = require('fs');

const GH = 'https://github.com/Bannysukumar';
const inv = JSON.parse(fs.readFileSync('scripts/inventory.json', 'utf8'));
const overrides = JSON.parse(fs.readFileSync('scripts/directory-overrides.json', 'utf8'));

// Topics that are profile-wide tags rather than project tech.
const NOISE_TOPICS = new Set(['banny-sukumar', 'open-source']);

const seen = new Set();
const entries = [];

for (const r of inv) {
  if (seen.has(r.name)) throw new Error(`Duplicate repo in inventory: ${r.name}`);
  seen.add(r.name);

  const o = overrides[r.name] || {};
  const topics = r.topics || [];
  const techTopics = topics.filter((t) => !NOISE_TOPICS.has(t)).slice(0, 3);

  const entry = {
    name: o.display || r.name,
    url: r.url || `${GH}/${r.name}`,
    tech: o.tech || r.language || techTopics.join(' · ') || 'No language reported',
    description: r.description || undefined,
    language: r.language || undefined,
    topics: topics.length ? topics : undefined,
    stars: r.stars || 0,
    updated: r.updated || undefined,
    archived: r.archived ? true : undefined,
    fork: r.fork ? true : undefined,
    liveUrl: o.liveUrl || undefined,
    // A live URL is only present when it returned HTTP 200; status records how it was verified.
    liveStatus: o.liveUrl ? o.liveStatus || 'responds-but-unrendered' : undefined,
    note: o.note || undefined,
  };
  // Drop undefined keys for a tidy generated file.
  for (const k of Object.keys(entry)) if (entry[k] === undefined) delete entry[k];
  entries.push(entry);
}

// Sanity checks — fail loudly rather than shipping a wrong catalogue.
const expected = inv.length;
if (entries.length !== expected) throw new Error(`Expected ${expected} entries, built ${entries.length}`);
if (entries.length !== new Set(entries.map((e) => e.url)).size) throw new Error('Duplicate repository URLs');

const render = (e) => {
  const lines = ['  {'];
  const fields = [
    ['name', JSON.stringify(e.name)],
    ['url', JSON.stringify(e.url)],
    ['tech', JSON.stringify(e.tech)],
    ['description', e.description !== undefined ? JSON.stringify(e.description) : null],
    ['language', e.language !== undefined ? JSON.stringify(e.language) : null],
    ['topics', e.topics ? JSON.stringify(e.topics) : null],
    ['stars', String(e.stars)],
    ['updated', e.updated !== undefined ? JSON.stringify(e.updated) : null],
    ['archived', e.archived ? 'true' : null],
    ['fork', e.fork ? 'true' : null],
    ['liveUrl', e.liveUrl !== undefined ? JSON.stringify(e.liveUrl) : null],
    ['liveStatus', e.liveStatus !== undefined ? JSON.stringify(e.liveStatus) : null],
    ['note', e.note !== undefined ? JSON.stringify(e.note) : null],
  ];
  const active = fields.filter(([, v]) => v !== null && v !== undefined);
  active.forEach(([k, v], i) => lines.push(`    ${k}: ${v}${i < active.length - 1 ? ',' : ''}`));
  lines.push('  },');
  return lines.join('\n');
};

const out = `/* AUTO-GENERATED by scripts/generate-directory.cjs — do not edit by hand.
 *
 * Canonical directory of every public repository on github.com/Bannysukumar.
 * Source: scripts/inventory.json (GitHub API snapshot, ${entries.length} repos)
 * merged with curated overrides in scripts/directory-overrides.json.
 *
 * Refresh:  node scripts/fetch-inventory.cjs && node scripts/generate-directory.cjs
 *
 * Live URLs are only listed when they returned HTTP 200 at verification time;
 * liveStatus records how each was verified (see LiveStatus in types/project.ts).
 */
import type { DirectoryEntry } from "../types/project";

export const directory: DirectoryEntry[] = [
${entries.map(render).join('\n')}
];
`;

fs.writeFileSync('src/data/directory.ts', out);
console.log(`src/data/directory.ts written: ${entries.length} entries`);
console.log('with liveUrl:', entries.filter((e) => e.liveUrl).length);
console.log('without description:', entries.filter((e) => !e.description).length);
console.log('forks:', entries.filter((e) => e.fork).length, '| archived:', entries.filter((e) => e.archived).length);
