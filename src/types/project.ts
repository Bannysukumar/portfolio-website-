/** Verification status of a project's live deployment. */
export type LiveStatus =
  /** HTTP 200 confirmed and the page rendered during research (Oct 2026). */
  | "verified-live"
  /** Server responds OK but the interactive render could not be confirmed. */
  | "responds-but-unrendered"
  /** Deployment recorded on the repo but currently returns 404. */
  | "deployment-missing"
  /** No live deployment; source code only. */
  | "source-only";

export interface RepoLink {
  /** Repository name on GitHub. */
  name: string;
  /** Full GitHub URL. */
  url: string;
  /** Primary language reported by GitHub. */
  language: string;
  /** What this repository contributes to the project. */
  role: string;
}

export interface LiveLink {
  url: string;
  status: LiveStatus;
  /** Evidence note, e.g. when and how the URL was verified. */
  note?: string;
}

export interface ProjectDetail {
  /** The problem the project addresses. */
  problem: string;
  /** How it is built — only claims supported by the repository. */
  approach: string[];
  /** Implementation notes taken from repo docs, if any. */
  notes?: string;
}

export interface Project {
  id: string;
  title: string;
  /** One-line category, e.g. "Full-stack platform". */
  category: string;
  /** Short editorial hook. */
  tagline: string;
  /** One or two factual sentences. */
  description: string;
  stack: string[];
  repos: RepoLink[];
  live?: LiveLink;
  /** Screenshot path under /images/projects, or an illustrative artwork. */
  thumbnail?: string;
  /** True when the artwork is an illustration, not a real screenshot. */
  thumbnailIllustrative?: boolean;
  features: string[];
  detail: ProjectDetail;
  featured: boolean;
}

/**
 * Canonical entry for the project directory — exactly one per public GitHub
 * repository. Generated by scripts/generate-directory.cjs from the GitHub API
 * snapshot merged with curated overrides; optional fields stay absent when the
 * repository provides no such data.
 */
export interface DirectoryEntry {
  /** Curated display name. */
  name: string;
  /** Canonical GitHub repository URL — unique per entry. */
  url: string;
  /** Curated or derived tech line, e.g. "React · Firebase". */
  tech: string;
  /** GitHub repository description; absent when the repository has none. */
  description?: string;
  /** Primary programming language reported by GitHub. */
  language?: string;
  /** GitHub topics, when the repository has any. */
  topics?: string[];
  /** Star count at inventory time. */
  stars?: number;
  /** Last push date (ISO 8601) at inventory time. */
  updated?: string;
  /** True when GitHub reports the repository as archived. */
  archived?: boolean;
  /** True when GitHub reports the repository as a fork. */
  fork?: boolean;
  /**
   * Live URL — only present when it returned HTTP 200 at verification time.
   * Absent means no working deployment link is offered.
   */
  liveUrl?: string;
  /** How the live URL was verified (only set alongside liveUrl). */
  liveStatus?: LiveStatus;
  /** Curated note, e.g. a recorded deployment that now returns 404. */
  note?: string;
}
